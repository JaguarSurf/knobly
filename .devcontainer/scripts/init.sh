#!/bin/bash

# Runs on the HOST before the container is created (devcontainer initializeCommand).

CURRENT_DIR=$(dirname "$0")
DEVCONTAINER_DIR="$CURRENT_DIR/.."
PROJECT_DIR="$DEVCONTAINER_DIR/.."

# Create .local folder
mkdir -p "$PROJECT_DIR/.local"
mkdir -p "$PROJECT_DIR/.local/share/opencode"
mkdir -p "$PROJECT_DIR/.claude"
mkdir -p "$PROJECT_DIR/.codex"

# Add permission for local host to access X server
if [ -f "/usr/bin/xhost" ]; then
  xhost +local:
else
  echo "xhost not found!"
fi

# ==== Init NVIDIA Compose ==== #

bash "$DEVCONTAINER_DIR/scripts/init_nvidia.sh"

# ==== Persistent tool data (bind mounts, see docker-compose.yaml) ==== #

# Created here, on the host, so they are owned by the host user (not by root, as Docker would do).
for dir in gradle android-sdk android-home tmp; do
  mkdir -p "$PROJECT_DIR/.local/devcontainer/$dir"
done
# Mounted as /tmp: world-writable with the sticky bit, like a regular /tmp.
chmod 1777 "$PROJECT_DIR/.local/devcontainer/tmp"

# ==== Host devices: KVM (Android emulator) and GPU (OpenGL) ==== #

# docker-compose.devices.yaml is generated (and git-ignored) because it depends on the host.
# Without a device, the corresponding entry is simply left out, so the container always starts:
#  - no /dev/kvm: the Android emulator is unavailable;
#  - no /dev/dri: OpenGL falls back to Mesa's software renderer (llvmpipe).

DEVICES_OVERRIDE="$DEVCONTAINER_DIR/docker-compose.devices.yaml"
DEVICES=()
GROUPS_TO_ADD=()

if [ -c /dev/kvm ]; then
  DEVICES+=("/dev/kvm:/dev/kvm")
  GROUPS_TO_ADD+=("$(stat -c '%g' /dev/kvm)")
  echo "KVM found: Android emulator enabled."
else
  echo "KVM not found: Android emulator disabled."
fi

if [ -d /dev/dri ]; then
  DEVICES+=("/dev/dri:/dev/dri")
  for node in /dev/dri/*; do
    [ -c "$node" ] && GROUPS_TO_ADD+=("$(stat -c '%g' "$node")")
  done
  echo "GPU found (/dev/dri): hardware OpenGL enabled."
else
  echo "GPU not found (/dev/dri): OpenGL uses software rendering."
fi

{
  echo "# Generated by .devcontainer/scripts/init.sh on the host. Do not edit."
  echo "services:"
  if [ ${#DEVICES[@]} -eq 0 ]; then
    echo "  devcontainer: {}"
  else
    echo "  devcontainer:"
    echo "    devices:"
    for device in "${DEVICES[@]}"; do echo "      - $device"; done
    echo "    group_add:"
    printf '%s\n' "${GROUPS_TO_ADD[@]}" | sort -un | while read -r gid; do echo "      - \"$gid\""; done
  fi
} > "$DEVICES_OVERRIDE"

# Remove the override generated by previous versions of this script.
rm -f "$DEVCONTAINER_DIR/docker-compose.kvm.yaml"
